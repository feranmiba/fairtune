#!/usr/bin/env python3
"""
Generates a valid, multi-page PDF Music Recording & Royalty Contract.
Pure Python implementation with no external library dependencies.
"""

import sys

def create_pdf(filename="sample_artist_recording_contract.pdf"):
    # Standard Letter: 612 x 792 points (8.5 x 11 inches)
    width, height = 612, 792
    margin_x = 54
    start_y = 730
    line_height = 14
    
    pages_text = []

    # PAGE 1
    p1 = [
        ("HEADER", "EXCLUSIVE ARTIST RECORDING & ROYALTY DISTRIBUTION AGREEMENT"),
        ("SUBHEADER", "Dated as of November 15, 2026"),
        ("SEP", ""),
        ("TEXT", "This EXCLUSIVE ARTIST RECORDING & ROYALTY DISTRIBUTION AGREEMENT (the \"Agreement\") is"),
        ("TEXT", "entered into by and between ASTRAL SOUNDWORKS RECORDS LLC, a Delaware limited liability"),
        ("TEXT", "company (\"Company\"), and MARCUS VANCE p/k/a \"VANCE ECHO\" (\"Artist\"), whose principal"),
        ("TEXT", "wallet address for on-chain royalty settlements is registered on the Stellar Testnet:"),
        ("BOLD", "Artist Wallet Address: GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5"),
        ("SEP", ""),
        ("HEADING", "WITNESSETH:"),
        ("TEXT", "WHEREAS, Company engages in the production, digital distribution, marketing, and monetization"),
        ("TEXT", "of high-fidelity musical sound recordings and decentralized music catalog administration; and"),
        ("TEXT", "WHEREAS, Artist is a professional recording artist, composer, and producer desiring to deliver"),
        ("TEXT", "new master recordings under transparent, auditable, and automated royalty split protocols;"),
        ("TEXT", "NOW, THEREFORE, in consideration of the mutual covenants herein contained, the parties agree:"),
        ("SEP", ""),
        ("SECTION", "SECTION 1. ENGAGEMENT AND MASTER RECORDING COMMITMENT"),
        ("TEXT", "1.1 Engagement: Company hereby engages Artist to render exclusive recording services to produce,"),
        ("TEXT", "record, and deliver one (1) full-length studio project consisting of ten (10) commercially satisfactory"),
        ("TEXT", "master recordings (\"Masters\")."),
        ("TEXT", "1.2 Delivery Schedule: Artist shall deliver the completed master audio stems, stereophonic mixes,"),
        ("TEXT", "and descriptive metadata (including ISRC and ISWC identifiers) no later than March 31, 2027."),
        ("SEP", ""),
        ("SECTION", "SECTION 2. TERRITORY AND GRANT OF RIGHTS"),
        ("TEXT", "2.1 Grant of Exclusive Rights: Artist hereby grants to Company the exclusive right to distribute,"),
        ("TEXT", "reproduce, publicly perform, stream, and license the Masters across all digital streaming platforms"),
        ("TEXT", "(DSPs), interactive audio transmissions, and synchronized audiovisual media."),
        ("TEXT", "2.2 Territory: The territory covered under this Agreement shall be the entire Universe."),
        ("TEXT", "2.3 Term: The initial term shall be three (3) years from the date of initial commercial release,"),
        ("TEXT", "subject to the reversion provisions set forth in Section 7."),
        ("SEP", ""),
        ("SECTION", "SECTION 3. ADVANCE AND RECOUPMENT SCHEDULE"),
        ("TEXT", "3.1 Advance: Promptly upon execution of this Agreement, Company shall pay to Artist an advance"),
        ("TEXT", "of Fifty Thousand United States Dollars ($50,000.00 USD), payable via confirmed Stellar settlement."),
        ("TEXT", "3.2 Non-Cross-Collateralization: The Advance shall be recoupable strictly from Artist's share of net"),
        ("TEXT", "receipts generated by the Masters. Under no circumstance shall the Advance be cross-collateralized"),
        ("TEXT", "against Artist's separate publishing royalties, mechanical royalties, or live performance revenue."),
    ]
    pages_text.append(p1)

    # PAGE 2
    p2 = [
        ("HEADER", "EXCLUSIVE ARTIST RECORDING & ROYALTY DISTRIBUTION AGREEMENT (PAGE 2)"),
        ("SEP", ""),
        ("SECTION", "SECTION 4. ROYALTY DISTRIBUTION AND ESCROW SPLITS"),
        ("TEXT", "4.1 Streaming Royalty Split: Company shall credit and disburse to Artist fifty percent (50.0%)"),
        ("TEXT", "of all Net Receipts derived from interactive digital streaming (e.g., Spotify, Apple Music, TIDAL)."),
        ("TEXT", "4.2 Sync and Licensing: Net receipts derived from synchronization licensing in motion pictures,"),
        ("TEXT", "television series, video games, or commercial advertisements shall be divided fifty-fifty (50/50)."),
        ("TEXT", "4.3 Collaborator Splits: The designated collaborators shall receive on-chain disbursements:"),
        ("BOLD", "  - Elena Rostova (Producer): 20.00% split (Wallet: GAAZI4TCR3TY5OJHCTJC2A4QSY6CJWJH5IAJTGKIN2ER7LBNVKOCCWN)"),
        ("BOLD", "  - Marcus Vance (Artist): 50.00% split (Wallet: GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5)"),
        ("BOLD", "  - Astral Soundworks LLC (Company): 30.00% split (Wallet: GCK3V7W74KTRG664TYL53N24S4H2M2Q7KTRN7K3S6H24225H2G7T4M2Y)"),
        ("SEP", ""),
        ("SECTION", "SECTION 5. ON-CHAIN SOROBAN RECONCILIATION AND SETTLEMENT"),
        ("TEXT", "5.1 Automated Settlement: All royalty revenues collected by Company shall be routed through a"),
        ("TEXT", "Stellar Soroban smart contract agreement. Once confirmed on-chain, distributions are non-custodial,"),
        ("TEXT", "instantaneous, and mathematically enforced according to agreed basis points."),
        ("TEXT", "5.2 Permitted Settlement Currencies: Disbursements shall be settled on-chain in Stellar USDC or"),
        ("TEXT", "native Lumens (XLM), with deterministic stroop rounding rules preventing remainder leakage."),
        ("SEP", ""),
        ("SECTION", "SECTION 6. ACCOUNTING AND AUDIT RIGHTS"),
        ("TEXT", "6.1 Accounting Statements: Company shall furnish quarterly digital statements detailing gross DSP"),
        ("TEXT", "revenues, platform deductions, net receipts, and recoupment ledger updates within 45 days of period close."),
        ("TEXT", "6.2 Audit Inspection: Artist shall have the unrestricted right, upon thirty (30) days prior written notice,"),
        ("TEXT", "to examine and audit the books, streaming records, and ledger logs of Company."),
        ("SEP", ""),
        ("SECTION", "SECTION 7. RIGHTS REVERSION AND DISPUTE RESOLUTION"),
        ("TEXT", "7.1 Rights Reversion: Upon the expiration of seven (7) years following initial release, all rights,"),
        ("TEXT", "master recording copyrights, and catalog distribution control shall automatically revert to Artist."),
        ("TEXT", "7.2 Governing Law: This Agreement shall be governed by the laws of the State of New York."),
        ("SEP", ""),
        ("HEADING", "IN WITNESS WHEREOF, the parties hereto have executed this Agreement as of the date first above written."),
        ("SEP", ""),
        ("BOLD", "COMPANY: ASTRAL SOUNDWORKS RECORDS LLC"),
        ("TEXT", "By: /s/ Julian Vance-Cole, Managing Director"),
        ("SEP", ""),
        ("BOLD", "ARTIST: MARCUS VANCE p/k/a \"VANCE ECHO\""),
        ("TEXT", "By: /s/ Marcus Vance (Wallet: GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5)"),
    ]
    pages_text.append(p2)

    # Build PDF Objects
    objects = []
    
    def add_object(content):
        objects.append(content)
        return len(objects)

    # 1: Catalog (will be obj 1)
    # 2: Pages root (will be obj 2)
    # Font Helvetica: obj 3
    # Font Helvetica-Bold: obj 4
    
    # We will reserve 1, 2, 3, 4
    # For each page: Page obj, Content stream obj
    total_pages = len(pages_text)
    page_obj_ids = []
    content_obj_ids = []

    # Fonts
    font_reg_id = 3
    font_bold_id = 4
    
    current_id = 4
    for i in range(total_pages):
        current_id += 1
        page_obj_ids.append(current_id)
        current_id += 1
        content_obj_ids.append(current_id)

    # Catalog
    catalog_str = f"<< /Type /Catalog /Pages 2 0 R >>"
    
    # Pages Root
    kids_str = " ".join([f"{pid} 0 R" for pid in page_obj_ids])
    pages_root_str = f"<< /Type /Pages /Kids [{kids_str}] /Count {total_pages} >>"

    font_reg_str = f"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
    font_bold_str = f"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>"

    obj_contents = [
        catalog_str,
        pages_root_str,
        font_reg_str,
        font_bold_str
    ]

    for i in range(total_pages):
        p_items = pages_text[i]
        
        # Build text stream
        stream_lines = []
        stream_lines.append("BT")
        
        y = start_y
        for kind, text in p_items:
            # Escape parenthesis
            safe_text = text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
            
            if kind == "HEADER":
                stream_lines.append(f"/F2 13 Tf")
                stream_lines.append(f"1 0 0 1 {margin_x} {y} Tm")
                stream_lines.append(f"({safe_text}) Tj")
                y -= 16
            elif kind == "SUBHEADER":
                stream_lines.append(f"/F1 10 Tf")
                stream_lines.append(f"1 0 0 1 {margin_x} {y} Tm")
                stream_lines.append(f"({safe_text}) Tj")
                y -= 14
            elif kind == "HEADING":
                y -= 6
                stream_lines.append(f"/F2 11 Tf")
                stream_lines.append(f"1 0 0 1 {margin_x} {y} Tm")
                stream_lines.append(f"({safe_text}) Tj")
                y -= 14
            elif kind == "SECTION":
                y -= 6
                stream_lines.append(f"/F2 10 Tf")
                stream_lines.append(f"1 0 0 1 {margin_x} {y} Tm")
                stream_lines.append(f"({safe_text}) Tj")
                y -= 13
            elif kind == "BOLD":
                stream_lines.append(f"/F2 9.5 Tf")
                stream_lines.append(f"1 0 0 1 {margin_x} {y} Tm")
                stream_lines.append(f"({safe_text}) Tj")
                y -= line_height
            elif kind == "SEP":
                y -= 6
            else: # TEXT
                stream_lines.append(f"/F1 9 Tf")
                stream_lines.append(f"1 0 0 1 {margin_x} {y} Tm")
                stream_lines.append(f"({safe_text}) Tj")
                y -= line_height

        stream_lines.append("ET")
        stream_body = "\n".join(stream_lines)
        stream_bytes = stream_body.encode("latin1")
        
        # Page object
        page_str = (
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {width} {height}] "
            f"/Resources << /Font << /F1 {font_reg_id} 0 R /F2 {font_bold_id} 0 R >> >> "
            f"/Contents {content_obj_ids[i]} 0 R >>"
        )
        obj_contents.append(page_str)
        
        # Stream object
        content_str = f"<< /Length {len(stream_bytes)} >>\nstream\n{stream_body}\nendstream"
        obj_contents.append(content_str)

    # Output file
    with open(filename, "wb") as f:
        f.write(b"%PDF-1.4\n")
        f.write(b"%\xe2\xe3\xcf\xd3\n")
        
        offsets = []
        for idx, obj in enumerate(obj_contents):
            obj_num = idx + 1
            offset = f.tell()
            offsets.append(offset)
            f.write(f"{obj_num} 0 obj\n".encode("latin1"))
            if isinstance(obj, str):
                f.write(obj.encode("latin1"))
            else:
                f.write(obj)
            f.write(b"\nendobj\n")
            
        xref_offset = f.tell()
        f.write(b"xref\n")
        f.write(f"0 {len(obj_contents) + 1}\n".encode("latin1"))
        f.write(b"0000000000 65535 f \n")
        for off in offsets:
            f.write(f"{off:010d} 00000 n \n".encode("latin1"))
            
        f.write(b"trailer\n")
        f.write(f"<< /Size {len(obj_contents) + 1} /Root 1 0 R >>\n".encode("latin1"))
        f.write(b"startxref\n")
        f.write(f"{xref_offset}\n".encode("latin1"))
        f.write(b"%%EOF\n")

    print(f"Successfully generated {filename} ({len(pages_text)} pages).")

if __name__ == "__main__":
    out_file = sys.argv[1] if len(sys.argv) > 1 else "sample_artist_recording_contract.pdf"
    create_pdf(out_file)
